/**
 * Список «Освойся в клубе».
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОН НУЖЕН
 *
 * Знакомство (шаг 4.6.1) спрашивает четыре вещи и ведёт к одному разбору.
 * Коротко оно именно потому, что остальное — фотография, первый эфир,
 * вход в чат — уезжает сюда. Без этого списка решение убрать фотографию
 * с первого экрана знакомства не имеет оправдания: отложенное просто
 * теряется.
 *
 * Отсюда два свойства, отличающие список от чек-листа задач:
 *
 * ОТМЕТКИ СТАВЯТСЯ САМИ. Ни один пункт нельзя отметить вручную — каждый
 * вычисляется из того, что человек действительно сделал. Список, в котором
 * можно поставить галочку не сделав, превращается в самообман и перестаёт
 * что-либо значить для платформы.
 *
 * СПИСОК ИСЧЕЗАЕТ. Сам, когда всё выполнено, и по кнопке — когда человек
 * решил, что ему это не нужно. Постоянно висящий на главной перечень
 * невыполненного — это упрёк, а взрослому хоббисту упрекать себя гитарой
 * незачем (см. отказ от стриков в PRD v0.1 §0 п.6).
 * ─────────────────────────────────────────────────────────────────
 *
 * Здесь только чистые правила: на вход — что человек уже сделал, на выход —
 * какие пункты выполнены и показывать ли список. Ни базы, ни запроса.
 */

/** Из чего складывается ответ на вопрос «что человек уже освоил» */
export type ChecklistFacts = {
  /** Загружена своя фотография, а не взята из Telegram */
  hasOwnAvatar: boolean
  /** Открыт хотя бы один разбор */
  openedSong: boolean
  /** Начат хотя бы один урок курса */
  startedCourse: boolean
  /** Открыта хотя бы одна запись эфира */
  watchedStream: boolean
  /** Нажата карточка перехода в чат клуба */
  openedChat: boolean
  /** Список скрыт человеком вручную */
  hiddenByUser: boolean
}

export type ChecklistItemKey = 'avatar' | 'song' | 'course' | 'stream' | 'chat'

export type ChecklistItem = {
  key: ChecklistItemKey
  title: string
  /** Зачем это стоит сделать. Не «выполните пункт», а польза для человека */
  hint: string
  done: boolean
}

/**
 * Порядок пунктов.
 *
 * Не по важности, а по возрастанию усилия. Первым идёт открыть разбор —
 * это то, зачем человек пришёл, и к моменту показа списка пункт обычно уже
 * выполнен: знакомство заканчивается кнопкой на разбор. Список, в котором
 * первая строка сразу отмечена, читается как «уже начал», а не как
 * «вот сколько тебе предстоит».
 *
 * Фотография последняя: она требует найти файл и потому дольше всего
 * остаётся невыполненной. Держать её первой значило бы месяцами показывать
 * список, начинающийся с невыполненного.
 */
const ITEM_ORDER: ChecklistItemKey[] = ['song', 'chat', 'stream', 'course', 'avatar']

const ITEM_TEXTS: Record<ChecklistItemKey, { title: string; hint: string }> = {
  song: {
    title: 'Открыть первый разбор',
    hint: 'Ради этого всё и затевалось',
  },
  chat: {
    title: 'Заглянуть в чат клуба',
    hint: 'Там спрашивают, когда что-то не выходит',
  },
  stream: {
    title: 'Посмотреть запись эфира',
    hint: 'Кураторы разбирают ошибки — часто ровно те, что у тебя',
  },
  course: {
    title: 'Начать курс',
    hint: 'Если разборы даются тяжело, начни отсюда',
  },
  avatar: {
    title: 'Поставить свою фотографию',
    hint: 'Клуб живее, когда видно, кто в нём',
  },
}

export function checklistItems(facts: ChecklistFacts): ChecklistItem[] {
  const done: Record<ChecklistItemKey, boolean> = {
    song: facts.openedSong,
    chat: facts.openedChat,
    stream: facts.watchedStream,
    course: facts.startedCourse,
    avatar: facts.hasOwnAvatar,
  }

  return ITEM_ORDER.map((key) => ({
    key,
    title: ITEM_TEXTS[key].title,
    hint: ITEM_TEXTS[key].hint,
    done: done[key],
  }))
}

export function completedCount(facts: ChecklistFacts): number {
  return checklistItems(facts).filter((item) => item.done).length
}

export const CHECKLIST_TOTAL = ITEM_ORDER.length

/**
 * Показывать ли список.
 *
 * Скрывается в двух случаях: всё выполнено или человек скрыл сам.
 * Третьего условия — «прошло столько-то дней» — намеренно нет: список
 * с двумя невыполненными пунктами полезен и через месяц, а исчезающий
 * по таймеру оставил бы человека без объяснения, куда он делся.
 */
export function isChecklistVisible(facts: ChecklistFacts): boolean {
  if (facts.hiddenByUser) return false

  return completedCount(facts) < CHECKLIST_TOTAL
}

/**
 * Заслуживает ли список поздравления.
 *
 * Показывается один раз — в тот заход, когда выполнен последний пункт.
 * Дальше список исчезает совсем. Это единственное место, где платформа
 * хвалит за прогресс, и именно поэтому оно уместно: похвала однократная
 * и по делу, а не механика удержания.
 */
export function isJustCompleted(previous: ChecklistFacts, current: ChecklistFacts): boolean {
  return (
    completedCount(previous) === CHECKLIST_TOTAL - 1 && completedCount(current) === CHECKLIST_TOTAL
  )
}
