import { index, integer, pgEnum, pgTable, primaryKey, text, uuid } from 'drizzle-orm/pg-core' // prettier-ignore

import { users } from '@/modules/identity/schema'
import { createdAt, primaryId, updatedAt } from '@/shared/db/columns'

import { FAVORITE_ENTITIES, NOTE_ENTITIES } from './types'

/**
 * Личная библиотека: что человек отложил на потом.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЭТО НЕ ПРОГРЕСС, И ХРАНИТЬ ВМЕСТЕ ИХ НЕЛЬЗЯ
 *
 * Обе таблицы про одного человека и обе полиморфные — соблазн
 * объединить сильный. Но пишутся они по-разному: прогресс ставит
 * плеер сам, каждые несколько секунд, а избранное — только человек,
 * руками. У них разный жизненный цикл и разные причины меняться.
 *
 * Смешав их, мы получили бы таблицу, где половина строк существует
 * ради `position_sec`, а половина — ради галочки, и каждый запрос
 * «что отложено» начинался бы с отсеивания второй половины.
 * ─────────────────────────────────────────────────────────────────
 */

/**
 * Что можно отложить.
 *
 * Перечень значений объявлен в `types.ts` и берётся оттуда — так браузер
 * получает список видов, не получая вместе с ним драйвер базы данных.
 * Обоснование целиком — там же.
 */
export const favoriteEntityEnum = pgEnum('favorite_entity', FAVORITE_ENTITIES)

export const favorites = pgTable(
  'favorites',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),

    entityType: favoriteEntityEnum('entity_type').notNull(),

    /**
     * Внешнего ключа на объект нет — так же, как у прогресса, и по той же
     * причине: ссылаться разом на три разные таблицы средствами базы
     * невозможно.
     *
     * Плата — висящая строка после удаления разбора. Она никому не мешает
     * и никому не видна: чтение всегда идёт через соединение с самим
     * объектом, и то, чего больше нет, в список просто не попадает.
     */
    entityId: uuid('entity_id').notNull(),

    createdAt: createdAt(),
  },
  (table) => [
    /*
     * Собственного идентификатора у строки нет намеренно: она полностью
     * определяется тройкой «кто, что, какое». «Отложить дважды» — не
     * событие, а то же самое состояние, и составной ключ делает вторую
     * вставку невозможной на уровне базы, а не на уровне внимательности.
     */
    primaryKey({ columns: [table.userId, table.entityType, table.entityId] }),

    // Главный и почти единственный запрос: «что я отложил», свежее сверху
    index('favorites_recent_idx').on(table.userId, table.createdAt.desc()),
  ],
)

/**
 * К чему привязывается заметка. Обоснование перечня — в `types.ts`.
 */
export const noteEntityEnum = pgEnum('note_entity', NOTE_ENTITIES)

/**
 * Личные заметки.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАМЕТКА ВСЕГДА ЛИЧНАЯ, И ОБЩЕЙ ОНА НЕ СТАНЕТ
 *
 * Ни поля «видна всем», ни привязки к автору-куратору. Это не упущение
 * и не задел: смысл заметки в том, что человек пишет её для себя
 * и в тех выражениях, в каких думает («опять лажаю на переходе»).
 * Стоит появиться зрителям — и писать перестают.
 *
 * Обсуждение разбора у платформы своё место имеет: комментарии
 * к разбору (PRD v0.1 §12, пункт 18) и чат клуба. Это другая сущность
 * с другим жизненным циклом, и делать её из заметок нельзя.
 * ─────────────────────────────────────────────────────────────────
 *
 * Внешнего ключа на объект нет по той же причине, что у избранного
 * и прогресса: сослаться разом на три таблицы средствами базы нельзя.
 * Заметка на удалённый разбор остаётся в базе, но нигде не показывается —
 * чтение идёт через соединение с самим объектом.
 */
export const userNotes = pgTable(
  'user_notes',
  {
    id: primaryId(),

    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),

    entityType: noteEntityEnum('entity_type').notNull(),
    entityId: uuid('entity_id').notNull(),

    body: text('body').notNull(),

    /**
     * Момент ролика в секундах или `null`.
     *
     * Необязательный намеренно. Половина заметок — про запись вообще
     * («вернуться, когда выучу баррэ»), и требовать для них время
     * значило бы заставлять человека выдумывать его.
     */
    timecodeSec: integer('timecode_sec'),

    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    // Заметки открытого разбора: главный запрос страницы содержимого
    index('user_notes_entity_idx').on(table.userId, table.entityType, table.entityId),
    // Страница «Мои заметки»: всё подряд, свежее сверху
    index('user_notes_recent_idx').on(table.userId, table.updatedAt.desc()),
  ],
)
