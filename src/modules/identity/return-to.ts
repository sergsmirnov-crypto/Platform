import { routes } from '@/shared/routes'

/**
 * Куда вернуть человека после входа.
 *
 * Адрес приходит параметром из middleware: человек шёл на закрытую страницу,
 * его отправили входить, и после входа он должен попасть туда, куда шёл.
 *
 * Здесь закрывается известная уязвимость — открытое перенаправление.
 * Если принимать параметр как есть, ссылка вида
 * `/?next=https://похожий-сайт.ru` уведёт человека на чужую страницу
 * сразу после успешного входа, причём выглядеть это будет совершенно
 * нормально: он ведь только что вошёл на настоящем сайте.
 *
 * Поэтому принимаются только внутренние адреса. Отдельно отсекается
 * форма `//чужой-сайт`: браузер трактует её как переход наружу,
 * хотя выглядит она как внутренний путь.
 */
export function safeReturnTo(raw: string | null | undefined): string {
  const fallback = routes.app.dashboard()

  if (!raw) return fallback
  if (!raw.startsWith('/')) return fallback
  if (raw.startsWith('//')) return fallback
  // Обратный слеш браузеры нормализуют в прямой: '/\злой-сайт' уводит наружу
  if (raw.startsWith('/\\')) return fallback

  return raw
}
