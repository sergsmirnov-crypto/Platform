/**
 * Имя cookie с сессией.
 *
 * Живёт здесь, а не в модуле `identity`, по одной причине: его читает
 * middleware, который выполняется в отдельной среде и не должен тянуть
 * за собой код работы с базой данных. Сама логика сессий — в модуле identity.
 *
 * Префикс `__Host-` — требование браузера: cookie с таким именем принимается
 * только по HTTPS, без указания домена и с путём `/`. Это защищает от подмены
 * cookie с соседнего поддомена.
 */
export const SESSION_COOKIE_NAME =
  process.env.NODE_ENV === 'production' ? '__Host-gc_session' : 'gc_session'

