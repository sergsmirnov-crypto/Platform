import 'server-only'

import { serverEnv } from './env.server'

/**
 * Секреты, которые нужны больше чем одному модулю.
 *
 * Секрет приложения подписывает и ключи сессий, и ключи воспроизведения
 * видео. Пока он был нужен одному модулю, доставать его прямо там было
 * правильно; со вторым потребителем начинается копирование сообщения
 * об ошибке, а следом — расхождение в проверках.
 *
 * Значения разводятся по назначению не здесь, а на месте использования:
 * каждый потребитель выводит из общего секрета свой ключ, чтобы подпись
 * одного назначения нельзя было принять за подпись другого.
 */
export function requireSessionSecret(): string {
  const secret = serverEnv.SESSION_SECRET

  if (!secret) {
    throw new Error(
      'Не задан секрет приложения (SESSION_SECRET). Сгенерировать: openssl rand -base64 32',
    )
  }

  return secret
}
