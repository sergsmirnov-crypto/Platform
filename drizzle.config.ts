import { defineConfig } from 'drizzle-kit'

/**
 * Настройка инструмента миграций.
 *
 * Миграции — это файлы с SQL-командами, которые приводят базу
 * к нужному состоянию. Они хранятся в git, применяются по порядку
 * и никогда не изменяются задним числом: если что-то пошло не так,
 * создаётся новая миграция, а не правится старая.
 */
export default defineConfig({
  /*
   * Схемы читаются прямо из модулей: добавили модуль с таблицами —
   * миграции увидят его автоматически, без правки общего файла.
   *
   * Вторым путём — общие перечисления. Без него инструмент видит
   * ссылки на такой тип в колонках, но не видит его объявления,
   * и в миграции не оказывается команды создать тип. Ошибка тихая:
   * файл миграции выглядит нормально и падает при применении.
   */
  schema: ['./src/modules/*/schema.ts', './src/shared/db/enums.ts'],
  out: './drizzle',
  dialect: 'postgresql',
  dbCredentials: {
    url: process.env.DATABASE_URL ?? '',
  },
  // Сообщения инструмента на английском, но подробные
  verbose: true,
  // Спрашивать подтверждение перед опасными операциями
  strict: true,
})
