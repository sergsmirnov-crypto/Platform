/**
 * Контрольные суммы текстов документов.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ЭТО НУЖНО
 *
 * Платформа записывает, с какой редакцией оферты согласился каждый
 * участник. Вся ценность этой записи держится на одном допущении:
 * текст редакции 2 никогда не менялся после того, как её опубликовали.
 *
 * Нарушить допущение легко и незаметно. Разработчик поправит опечатку
 * в пункте 5.4, номер редакции трогать не станет — правка же
 * косметическая, — и с этого момента полторы сотни записей «согласился
 * с редакцией 2» указывают на текст, которого никто из участников
 * не видел. Обычное ревью такую правку пропускает: она выглядит
 * безобидно и по сути безобидна, пока не начинается спор.
 *
 * Поэтому текст защищён снаружи: тест считает сумму и сравнивает
 * с записанной. Любое изменение текста — падение сборки с прямым
 * указанием, что делать: либо вернуть текст, либо увеличить номер
 * редакции и обновить сумму здесь.
 *
 * Приём нестандартный, и это осознанно: обычные способы (ревью, договорённость
 * в документации) здесь не работают, потому что ошибка не выглядит ошибкой.
 * ─────────────────────────────────────────────────────────────────
 *
 * Как обновить: `pnpm legal:checksums` выведет актуальные значения.
 */
export type DocumentChecksum = {
  /** Редакция, к которой относится сумма. Обязана совпадать с документом */
  version: number
  /** SHA-256 от `body` документа, в шестнадцатеричном виде */
  sha256: string
}

