import { redirect } from 'next/navigation'

import { routes } from '@/shared/routes'

type Props = { params: Promise<{ module: string }> }

/**
 * Отдельной страницы модуля нет.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПЕРЕНАПРАВЛЕНИЕ, А НЕ ЕЩЁ ОДИН ЭКРАН
 *
 * В карте экранов (PRD §3.1) страница модуля была. При проектировании
 * карты курса выяснилось, что показывать ей нечего: всё содержимое
 * модуля — это список его уроков, и он уже виден на карте курса,
 * причём вместе с соседними модулями, то есть с ответом на вопрос
 * «сколько ещё осталось».
 *
 * Отдельный экран дублировал бы карту, отняв контекст. Поэтому адрес
 * сохраняется — ссылки на модуль из старых сообщений в чате должны
 * работать, — но ведёт на карту курса, к нужному модулю.
 * ─────────────────────────────────────────────────────────────────
 */
export default async function CourseModulePage({ params }: Props) {
  const { module: moduleSlug } = await params

  redirect(`${routes.app.learn.course()}#${moduleSlug}`)
}
