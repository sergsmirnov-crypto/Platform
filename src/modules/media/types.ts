import type { MediaKind } from './domain'

/**
 * Что модуль медиа отдаёт наружу.
 *
 * Как и в разборах, типы описаны здесь, а не выведены из таблицы:
 * таблица — способ хранения, а не договор с интерфейсом. Наружу
 * не уходит ни ключ файла в хранилище, ни имя поставщика — интерфейсу
 * они не нужны, а в разметке страницы им тем более не место.
 */

/** Файл в том виде, в каком его показывают участнику */
export type MaterialAsset = {
  id: string
  kind: MediaKind
  /** Готовая подпись: своя или по виду файла */
  title: string
  sizeLabel: string | null
  /** Готов ли файл к выдаче — обработка занимает время */
  isReady: boolean
  /** Можно ли получить ссылку на скачивание */
  isDownloadable: boolean
  /** Внешний адрес: интерактивные табы живут на чужой странице */
  externalUrl: string | null
}

/**
 * Материал в редакторе куратора.
 *
 * Отличается от `MaterialAsset` тем, ради чего вообще существует
 * отдельный тип: куратору нужна его собственная подпись как есть,
 * чтобы поле ввода показывало пустоту там, где подписи нет, а не
 * подставленное «Табы (PDF)», которое он потом «сохранит» как настоящее.
 */
export type EditorMaterial = {
  /** Идентификатор привязки. Именно он адресуется при правке и удалении */
  id: string
  assetId: string
  kind: MediaKind
  /** Подпись куратора как есть: `null` — подписи нет */
  title: string | null
  /** Что показать в списке: подпись или название вида файла */
  displayTitle: string
  sizeLabel: string | null
  isReady: boolean
  isDownloadable: boolean
  isExternal: boolean
  externalUrl: string | null
}

/**
 * Разрешение на скачивание.
 *
 * Возвращается сервисом после всех проверок. Срок жизни ссылки короткий
 * намеренно: пересылать её бесполезно (PRD v0.2 §2.1).
 */
export type DownloadTicket = {
  url: string
  /** Имя, под которым файл сохранится у человека */
  fileName: string
  expiresInSeconds: number
}

/**
 * Разрешение на просмотр.
 *
 * Собирается сервером и уезжает в компонент плеера целиком. Компонент
 * не знает ни названия хостинга, ни того, как получился адрес: он умеет
 * только показать то, что ему дали.
 */
export type PlaybackTicket = {
  /** Адрес ролика для плеера. Пустая строка — хостинг не подключён */
  url: string
  watermark: string
  chapters: { position: number; title: string }[]
  /** С какой секунды начинать. `null` — с начала */
  startSec: number | null
}

/**
 * Материал, привязанный к содержимому: табы, Guitar Pro, минусовка.
 *
 * Живёт в модуле медиа, а не в разборах, хотя появился именно там:
 * тот же список показывают страница песни, урок курса и запись эфира.
 * Три одинаковых типа в трёх модулях разошлись бы при первой правке,
 * а копия компонента списка — при второй.
 *
 * Отличается от `MaterialAsset` одним полем — идентификатором привязки.
 * Он нужен как ключ списка: один и тот же файл может быть привязан
 * к нескольким объектам, и `assetId` в качестве ключа однажды
 * повторился бы.
 */
export type MaterialView = {
  /** Идентификатор привязки, а не файла */
  id: string
  title: string
  kind: MediaKind
  mediaAssetId: string
  isDownloadable: boolean
  sizeLabel: string | null
  /** Готов ли файл: обработка после загрузки занимает время */
  isReady: boolean
  /** Внешний адрес — только у интерактивных табов */
  externalUrl: string | null
}
