import { z } from 'zod'

/**
 * Типы и схемы проверки модуля библиотеки.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПЕРЕЧЕНЬ ВИДОВ ЖИВЁТ ЗДЕСЬ, А НЕ В `schema.ts`
 *
 * Обычно в проекте наоборот: перечисление объявляет таблица, а код
 * берёт значения оттуда (так сделано у прогресса). Здесь пришлось
 * развернуть зависимость, и причина стоит того, чтобы её записать.
 *
 * Кнопка «Отложить» — компонент браузера. Ей нужен тип вида и подписи,
 * то есть она обращается к публичному входу модуля. Если бы перечень
 * лежал в `schema.ts`, вместе с ним в браузер уехал бы драйвер базы
 * данных — сотни килобайт кода, который там не нужен и не выполнится.
 *
 * Поэтому перечень объявлен здесь, а таблица берёт его: `types.ts`
 * не знает ни о базе, ни о сервере, и попасть в браузер ему не стыдно.
 * ─────────────────────────────────────────────────────────────────
 *
 * ⚠️ Песня, а не вариант разбора — в отличие от прогресса.
 *
 * Прогресс живёт на варианте: человек проходит конкретный уровень
 * конкретного куратора. Откладывают же «Nothing Else Matters», а не
 * «средний уровень от Ивана»: перейдя с начального уровня на средний,
 * человек не должен обнаружить, что отложенное осыпалось.
 *
 * Части разбора и модули курса в перечень не входят: у части нет своей
 * страницы, открывать в отложенном было бы нечего (ADR-0023).
 */
export const FAVORITE_ENTITIES = ['song', 'stream', 'lesson'] as const

export type FavoriteEntity = (typeof FAVORITE_ENTITIES)[number]

/** Ссылка на отложенный объект: всё, что модуль о нём знает */
export type FavoriteRef = {
  entityType: FavoriteEntity
  entityId: string
}

/** Отложенное вместе с датой — для сортировки и подписи «отложено вчера» */
export type FavoriteRow = FavoriteRef & {
  createdAt: Date
}

/**
 * К чему привязывается заметка.
 *
 * ⚠️ Здесь вариант разбора, а не песня — в отличие от избранного.
 *
 * И это не непоследовательность, а разная природа. Отложить — намерение
 * про произведение: «хочу разобрать эту песню». Заметка привязана
 * к моменту конкретного ролика: «на 2:14 перестроить палец». Ролик
 * принадлежит варианту, и у среднего уровня он другой, чем у начального.
 *
 * Перенести заметку на песню целиком означало бы показывать пометку
 * про 2:14 человеку, открывшему другую запись, где на 2:14 совсем другое.
 */
export const NOTE_ENTITIES = ['arrangement', 'lesson', 'stream'] as const

export type NoteEntity = (typeof NOTE_ENTITIES)[number]

export type NoteRef = {
  entityType: NoteEntity
  entityId: string
}

/** Заметка целиком — то, что показывается человеку */
export type Note = NoteRef & {
  id: string
  body: string
  /** Момент ролика или `null`, если заметка про запись вообще */
  timecodeSec: number | null
  createdAt: Date
  updatedAt: Date
}

export const favoriteEntitySchema = z.enum(FAVORITE_ENTITIES)

export const noteEntitySchema = z.enum(NOTE_ENTITIES)

export const favoriteRefSchema = z.object({
  entityType: favoriteEntitySchema,
  entityId: z.uuid(),
})

export const noteRefSchema = z.object({
  entityType: noteEntitySchema,
  entityId: z.uuid(),
})
