import { cleanupStalledUploads } from '@/modules/media/upload-service'
import { appConfig } from '@/shared/config/app.config'
import { getLogger } from '@/shared/logger'

/**
 * Уборка оборванных загрузок.
 *
 * Загрузка файла записывается в базу до того, как байты доедут: так
 * ключ хранилища известен заранее, и незавершённая загрузка оставляет
 * след. Обратный порядок оставлял бы в хранилище файлы, о которых
 * никто не помнит, — а перечислять содержимое хранилища мы не умеем
 * и уметь не хотим.
 *
 * Цена такого решения — строки в состоянии «загружается», которые
 * никогда не станут готовыми. Их и убирает эта задача, вместе с тем,
 * что успело попасть в хранилище.
 *
 * Почему ночью, а не сразу после сбоя: «сразу» не бывает. Браузер,
 * закрытый на середине отправки, ничего серверу не сообщает — узнать
 * о брошенной загрузке можно только по прошествии времени.
 */
export async function runMediaCleanup(): Promise<void> {
  const removed = await cleanupStalledUploads(appConfig.media.stalledUploadHours)

  getLogger().info({ job: 'media.cleanup', removed }, 'уборка оборванных загрузок выполнена')
}
