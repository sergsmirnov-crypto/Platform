/**
 * Правила показа видео: что написать на водяном знаке и как собрать
 * оглавление.
 *
 * Ни базы, ни сети — чистые функции, покрытые тестами. Водяной знак
 * особенно: ошибка в нём либо оставит запись неподписанной, либо покажет
 * участнику лишнее о нём самом на весь экран.
 */

/** Часть разбора в том виде, в каком она нужна для оглавления */
export type ChapterSource = {
  title: string
  /** С какой секунды общего ролика начинается часть */
  startSec: number | null
}

/**
 * Текст водяного знака.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЧТО ПИШЕМ И ПОЧЕМУ ИМЕННО ЭТО
 *
 * Имя участника и его псевдоним в Telegram. Не почта, не идентификатор
 * записи в базе, не номер телефона.
 *
 *   • Имя работает социально: человек не сольёт файл, на котором крупно
 *     написано его имя, в чат, где сидят его же знакомые. Это и есть
 *     главная мера против пересылки (PRD v0.2 §2.2).
 *   • Псевдоним нужен нам: имена в клубе повторяются, а по псевдониму
 *     источник утечки находится за секунды.
 *   • Почта и телефон не пишутся никогда. Кадр с чужого экрана
 *     разлетается дальше, чем видео, и превращать водяной знак в утечку
 *     персональных данных нельзя.
 *
 * Знак не отключается настройкой. Возможность «показывать без знака»
 * однажды окажется включённой по умолчанию.
 * ─────────────────────────────────────────────────────────────────
 */
export function watermarkText(viewer: { displayName: string; username?: string | null }): string {
  const name = viewer.displayName.trim() || 'Участник клуба'
  const username = viewer.username?.trim()

  return username ? `${name} · @${username.replace(/^@/, '')}` : name
}

/**
 * Оглавление для дорожки плеера.
 *
 * Части разбора становятся точками на полосе воспроизведения: человек
 * приходит доучить соло и попадает в него, не перематывая час записи.
 *
 * Части без времени начала отбрасываются: у них своё видео, а не отрезок
 * общего, и в оглавление общего ролика им попадать нечем. Первая точка
 * с нулевой секунды добавляется всегда — без неё начало ролика выглядит
 * как «часть, о которой забыли».
 */
export function buildChapters(
  sections: readonly ChapterSource[],
): { position: number; title: string }[] {
  const points = sections
    .filter((section): section is ChapterSource & { startSec: number } => section.startSec !== null)
    .map((section) => ({ position: section.startSec, title: section.title }))
    .sort((left, right) => left.position - right.position)

  if (points.length === 0) return []

  return points[0]?.position === 0 ? points : [{ position: 0, title: 'Начало' }, ...points]
}

/**
 * Сколько живёт ключ воспроизведения.
 *
 * Это НЕ срок доступа к видео: доступ проверяется заново при каждом
 * запросе от видеохостинга, по живому состоянию подписки. Срок жизни
 * ключа ограничивает только то, как долго можно пользоваться строкой,
 * подсмотренной в исходном коде страницы.
 *
 * Два часа — компромисс. Меньше нельзя: эфир идёт полтора часа,
 * и ключ, истёкший на середине, оборвёт просмотр. Больше незачем.
 */
export const PLAYBACK_TOKEN_TTL_SECONDS = 2 * 60 * 60
