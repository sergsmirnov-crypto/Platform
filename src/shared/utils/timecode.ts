/**
 * Таймкоды: «2:14» ↔ 134 секунды.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ В ОБЩЕМ СЛОЕ, А НЕ В МОДУЛЕ
 *
 * Началось с частей разбора, продолжилось оглавлением эфира, а редактор
 * оглавления понадобился обоим. К моменту переезда одна и та же функция
 * была написана дважды — в разборах и в правилах эфиров — и уже слегка
 * разошлась в поведении на отрицательных числах.
 *
 * Превращение времени в текст и обратно — не бизнес-правило чего-то
 * одного, а инструмент. Место инструментов — здесь.
 * ─────────────────────────────────────────────────────────────────
 *
 * Это место редактора, где ошибка тише всего и дороже всего: неверно
 * распознанное «2:14» отправит участника не туда, и жалоба придёт
 * не от куратора, а от участника через неделю.
 */

/**
 * «2:14» → 134 секунды.
 *
 * Принимает и «134», и «2:14», и «1:02:30»: куратор переписывает то,
 * что видит в плеере, а видит он там разное в зависимости от длины
 * ролика. Пустая строка означает «таймкод не указан», а не ноль.
 */
export function parseTimecode(value: string): number | null {
  const trimmed = value.trim()
  if (!trimmed) return null

  const parts = trimmed.split(':').map((part) => Number.parseInt(part, 10))
  if (parts.some((part) => Number.isNaN(part))) return null

  return parts.reduce((total, part) => total * 60 + part, 0)
}

/**
 * 134 → «2:14».
 *
 * `null` — это «не указано» и даёт пустую строку: в поле формы должно
 * быть пусто, а не «0:00», иначе куратор решит, что значение уже задано.
 * Отрицательное значение до подписи доехать не должно, но если доехало —
 * показываем начало записи, а не «-1:-10».
 */
export function formatTimecode(seconds: number | null): string {
  if (seconds === null) return ''

  const safe = Math.max(0, Math.round(seconds))
  const hours = Math.floor(safe / 3600)
  const minutes = Math.floor((safe % 3600) / 60)
  const rest = safe % 60

  const pad = (value: number) => String(value).padStart(2, '0')

  return hours > 0 ? `${hours}:${pad(minutes)}:${pad(rest)}` : `${minutes}:${pad(rest)}`
}
