import { boolean, index, integer, pgTable, text, uniqueIndex, uuid } from 'drizzle-orm/pg-core'

import { users } from '@/modules/identity/schema'
import { createdAt, updatedAt } from '@/shared/db/columns'

/**
 * Карточка куратора.
 *
 * ─────────────────────────────────────────────────────────────────
 * РАСШИРЕНИЕ УЧАСТНИКА, А НЕ ОТДЕЛЬНЫЙ ЧЕЛОВЕК
 *
 * Первичный ключ — это идентификатор участника. Куратор не заводится
 * заново: он уже есть в клубе, у него есть профиль, прогресс и подписка.
 * Карточка добавляет к нему публичную часть — то, что видят участники
 * на странице «Кураторы».
 *
 * Отдельная таблица, а не поля в `users`, по двум причинам. Первая:
 * этих полей десяток, и у ста пятидесяти участников из ста пятидесяти
 * они пустые. Вторая: у карточки своя жизнь — её скрывают, показывают,
 * переставляют местами, — и мешать это с личным профилем значит
 * получить таблицу, в которой не разобраться.
 * ─────────────────────────────────────────────────────────────────
 *
 * Адресное имя хранится здесь, а не собирается из имени участника:
 * ссылку на страницу куратора кидают в чат, и она не должна ломаться
 * от того, что человек поменял имя в профиле.
 */
export const curatorProfiles = pgTable(
  'curator_profiles',
  {
    userId: uuid('user_id')
      .primaryKey()
      .references(() => users.id, { onDelete: 'cascade' }),

    slug: text('slug').notNull(),

    /** Одна строка: «Фингерстайл и акустика». Она же — подпись в списке */
    headline: text('headline'),

    /** Развёрнутый рассказ о себе как о преподавателе */
    bio: text('bio'),

    /** Чему учит: «бой», «перебор», «соло» */
    teaches: text('teaches').array().notNull().default([]),

    /** На ком вырос: список групп и музыкантов */
    influences: text('influences').array().notNull().default([]),

    /** Инструменты и техника — обычный вопрос от участников */
    gear: text('gear').array().notNull().default([]),

    /** Год начала преподавания: стаж считается от него, а не хранится числом */
    teachingSince: integer('teaching_since'),

    /**
     * Показывать ли карточку.
     *
     * Скрытая карточка не удаляется: куратор может уйти в отпуск
     * на полгода, а его разборы остаются, и связь «кто вёл» тоже
     */
    isPublic: boolean('is_public').notNull().default(false),

    /**
     * Порядок в списке.
     *
     * Задаётся руками: кураторы — это люди, и алфавитный порядок здесь
     * не нейтрален, а случаен. Основатель клуба должен стоять первым
     * независимо от буквы, с которой начинается его имя
     */
    orderIndex: integer('order_index').notNull().default(0),

    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex('curator_profiles_slug_idx').on(table.slug),
    index('curator_profiles_order_idx').on(table.orderIndex),
  ],
)
