import { z } from 'zod'

/**
 * Адрес электронной почты: проверка и приведение к одному виду.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ПРИВОДИТЬ К ОДНОМУ ВИДУ
 *
 * Адрес — ключ, по которому человек находится при входе. «Ivan@Mail.ru»
 * и «ivan@mail.ru » — один и тот же ящик, но для базы это две разные
 * строки. Без приведения человек, однажды набравший адрес с заглавной
 * буквы, при следующем входе получил бы второй, пустой аккаунт — без
 * прогресса и без подписки — и решил бы, что всё пропало.
 *
 * Регистр приводится целиком, включая часть до «@». Формально почтовый
 * сервер вправе различать регистр в имени ящика, но на практике этого
 * не делает ни один распространённый сервис, а цена обратного решения —
 * задвоенные аккаунты.
 * ─────────────────────────────────────────────────────────────────
 *
 * Функции чистые: ни сети, ни базы. Существует ли ящик на самом деле,
 * проверяет не формат, а письмо с кодом.
 */

/** Самый длинный адрес, допустимый стандартом почты */
export const MAX_EMAIL_LENGTH = 254

export function normalizeEmail(raw: string): string {
  return raw.trim().toLowerCase()
}

/**
 * Схема поля «почта» для форм и действий сервера.
 *
 * Возвращает уже приведённый адрес: остальной код никогда не видит
 * адрес в том виде, в каком его набрали.
 */
export const emailSchema = z
  .string({ error: 'Введите адрес почты' })
  .transform(normalizeEmail)
  .pipe(
    z
      .email({ error: 'Похоже, в адресе ошибка. Проверьте, пожалуйста' })
      .max(MAX_EMAIL_LENGTH, { error: 'Слишком длинный адрес' }),
  )

/**
 * Адрес в маскированном виде: «iv***@mail.ru».
 *
 * Для экрана «код отправлен на…»: человек узнаёт свой адрес, а случайный
 * зритель через плечо — нет. И для журнала: адрес — персональные данные.
 */
export function maskEmail(email: string): string {
  const at = email.lastIndexOf('@')
  if (at <= 0) return '***'

  const name = email.slice(0, at)
  const domain = email.slice(at + 1)
  const visible = name.length <= 2 ? name.slice(0, 1) : name.slice(0, 2)

  return `${visible}***@${domain}`
}
