import { timestamp, uuid } from 'drizzle-orm/pg-core'
import { v7 as uuidv7 } from 'uuid'

/**
 * Общие определения колонок.
 *
 * Собраны в одном месте, чтобы во всех таблицах они были одинаковыми.
 * Иначе через год в одной таблице окажется `created_at` с часовым поясом,
 * а в другой без — и сравнение дат начнёт врать.
 */

/**
 * Первичный ключ — UUID версии 7.
 *
 * Обычный случайный UUID (v4) плохо ложится в индекс: новые записи попадают
 * в случайные места, индекс разрастается и замедляется. UUID v7 содержит
 * внутри метку времени, поэтому записи идут по порядку — как обычный
 * счётчик, но без раскрытия количества записей наружу.
 *
 * Значение вычисляется приложением, а не базой. Причина практическая:
 * встроенная функция `uuidv7()` появилась только в PostgreSQL 18, и привязка
 * к ней потребовала бы обновления базы на всех окружениях. Плюс приложение
 * знает идентификатор ещё до записи — это упрощает связанные вставки
 * и журналирование.
 */
export const primaryId = () =>
  uuid('id')
    .primaryKey()
    .$defaultFn(() => uuidv7())

/** Момент создания записи */
export const createdAt = () =>
  timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow()

/** Момент последнего изменения */
export const updatedAt = () =>
  timestamp('updated_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow()

/**
 * Мягкое удаление.
 *
 * Запись не стирается, а помечается удалённой. Это сохраняет связи:
 * удалённый участник не ломает историю подписок и авторство разборов.
 */
export const deletedAt = () => timestamp('deleted_at', { withTimezone: true, mode: 'date' })

/** Все временные метки — всегда с часовым поясом, всегда в UTC */
export const timestampTz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' })
