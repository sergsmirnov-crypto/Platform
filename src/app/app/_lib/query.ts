/**
 * Разбор параметров адресной строки.
 *
 * Общее место для двух функций, которые до этого были написаны дважды —
 * на странице разбора и на странице эфира — и начали расходиться:
 * одна отбрасывала нулевую секунду, другая нет.
 *
 * Значения приходят из адреса, то есть их может напечатать кто угодно.
 * Поэтому всё непонятное молча превращается в `null`: отвечать страницей
 * ошибки на опечатку в ссылке — значит наказывать человека за неё.
 */

/** Параметр может прийти списком: `?level=a&level=b`. Берём первый */
export function single(value: string | string[] | undefined): string | null {
  const first = Array.isArray(value) ? value[0] : value

  return first?.trim() || null
}

/**
 * Секунда из параметра `?t=134`.
 *
 * Ноль отбрасывается вместе с отрицательными: «открой запись с самого
 * начала» — это и есть обычное открытие, отдельного параметра для него
 * не нужно. Верхняя граница — сутки, втрое больше самой длинной записи.
 */
export function parseSeconds(value: string | string[] | undefined): number | null {
  const parsed = Number.parseInt(single(value) ?? '', 10)

  if (!Number.isFinite(parsed) || parsed <= 0 || parsed > 24 * 60 * 60) return null

  return parsed
}
