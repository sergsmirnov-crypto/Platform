/** Кому и что показываем — всё, что нужно хостингу для одного просмотра */
export type PlaybackRequest = {
  /** Идентификатор ролика у хостинга */
  videoId: string
  /** Подписанный ключ: по нему хостинг спросит у нас разрешение */
  token: string
  /**
   * Текст водяного знака: имя участника.
   *
   * Главная мера против пересылки записи в чужой чат. Человек не сольёт
   * файл, на котором крупно написано его имя, туда, где сидят его же
   * знакомые (PRD v0.2 §2.2)
   */
  watermark: string
  /** Оглавление: части разбора становятся точками на дорожке плеера */
  chapters: { position: number; title: string }[]
  /** С какой секунды начинать. Нужно, когда часть — отрезок общего ролика */
  startSec: number | null
}

/**
 * Всё, что нужно браузеру, чтобы показать плеер.
 *
 * Возвращается уже собранным: компонент плеера не занимается сборкой
 * адресов и не знает названия хостинга.
 */
export type PlaybackSource = {
  /** Адрес ролика для плеера */
  url: string
  watermark: string
  chapters: { position: number; title: string }[]
  startSec: number | null
}

export type VideoProvider = {
  /** Имя поставщика — для журнала и диагностики */
  readonly name: string
  /** Умеет ли поставщик что-то показывать. `false` у заглушки */
  readonly isEnabled: boolean

  /** Собирает всё, что нужно плееру для одного просмотра */
  buildSource(request: PlaybackRequest): PlaybackSource
}
