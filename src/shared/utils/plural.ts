/**
 * Русское склонение слова после числа.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ СВОЯ ФУНКЦИЯ, А НЕ БИБЛИОТЕКА ЛОКАЛИЗАЦИИ
 *
 * Аудитория русскоязычная (ARCHITECTURE §12). Библиотека локализации
 * ради трёх форм слова тянула бы правила всех языков мира, свой формат
 * файлов с переводами и обёртки вокруг каждой строки интерфейса.
 * Здесь семь строк кода и один тест.
 *
 * Появилась после того, как одна и та же функция оказалась написана
 * трижды — в разборах, в эфирах и в текстах эфиров. Четвёртой копии
 * быть не должно.
 * ─────────────────────────────────────────────────────────────────
 *
 * @example plural(3, 'пункт', 'пункта', 'пунктов') // 'пункта'
 */
export function plural(count: number, one: string, few: string, many: string): string {
  // Одиннадцать–четырнадцать — исключение: «одиннадцать пунктов»,
  // хотя обычное правило по последней цифре дало бы «пункт»
  const mod100 = Math.abs(count) % 100
  if (mod100 >= 11 && mod100 <= 14) return many

  const mod10 = Math.abs(count) % 10
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few

  return many
}
