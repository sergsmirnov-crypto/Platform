/**
 * Превращает произвольную строку в фрагмент адреса страницы.
 *
 * Нужен уже сейчас, чтобы на шаге F0 было что проверить тестами,
 * и будет использоваться с Этапа 5: адреса разборов, эфиров и уроков
 * собираются из названия песни («Кино — Перемен» → `kino-peremen`).
 *
 * Кириллица транслитерируется, а не выбрасывается: иначе у русских песен
 * адрес получился бы пустым.
 */

const CYRILLIC_MAP: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'c',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
}

/** Максимальная длина адреса. Длиннее — нечитаемо и неудобно в ссылках. */
const MAX_LENGTH = 80

export function slugify(input: string): string {
  const transliterated = Array.from(input.toLowerCase())
    .map((char) => CYRILLIC_MAP[char] ?? char)
    .join('')

  return transliterated
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // убираем диакритику: é → e
    .replace(/[^a-z0-9]+/g, '-') // всё остальное превращается в дефис
    .replace(/^-+|-+$/g, '') // дефисы по краям не нужны
    .slice(0, MAX_LENGTH)
    .replace(/-+$/g, '') // обрезка могла оставить дефис в конце
}
