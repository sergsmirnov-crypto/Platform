import { appConfig } from '@/shared/config/app.config'

/**
 * Приветствие на главной.
 *
 * Вынесено отдельной чистой функцией: правило «во сколько начинается
 * вечер» — из тех, что хочется поправить, не трогая разметку, и стоит
 * покрыть тестом, чтобы в полночь не здоровались «добрым днём».
 */

/**
 * @param hour час по местному времени клуба, 0–23
 */
export function greetingFor(hour: number): string {
  if (hour >= 5 && hour < 12) return 'Доброе утро'
  if (hour >= 12 && hour < 18) return 'Добрый день'
  if (hour >= 18 && hour < 23) return 'Добрый вечер'
  return 'Доброй ночи'
}

/**
 * Час по времени клуба.
 *
 * Время берётся не с устройства человека, а из настроек платформы.
 * Причина: страница собирается на сервере, и его часовой пояс к делу
 * отношения не имеет, а перенос приветствия в браузер потребовал бы
 * отрисовывать его дважды — сначала пустым, потом настоящим.
 *
 * Следствие: у десятка участников за рубежом приветствие может
 * не совпасть со временем суток. Цена ошибки — одно слово, поэтому
 * усложнять ради неё не стоит.
 */
export function currentClubHour(now: Date = new Date()): number {
  const formatted = new Intl.DateTimeFormat('ru-RU', {
    timeZone: appConfig.timezone,
    hour: 'numeric',
    hour12: false,
  }).format(now)

  return Number.parseInt(formatted, 10)
}
