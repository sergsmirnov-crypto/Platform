import 'server-only'

import { serverEnv } from '@/shared/config/env.server'

/**
 * Доступен ли служебный вход.
 *
 * Вынесено в отдельный файл по требованию Next.js: файл с пометкой
 * `'use server'` может экспортировать только асинхронные функции,
 * а эта проверка синхронная и должна оставаться такой — её вызывают
 * страницы, чтобы решить, существуют ли они вообще.
 *
 * Защита построена на `NODE_ENV`, а не на отдельной переменной окружения.
 * Причина: чем меньше переключателей, тем меньше способов случайно
 * оставить открытой дверь на боевом сервере. В производственной сборке
 * `NODE_ENV` равен `production` всегда, и изменить это из файла настроек
 * нельзя.
 */
export function isDevAuthAvailable(): boolean {
  return serverEnv.NODE_ENV === 'development'
}
