/**
 * Переключатели, влияющие на поведение приложения целиком.
 *
 * Отличаются от фиче-флагов из базы данных (те появятся позже и управляются
 * из интерфейса): эти читаются из окружения и нужны на самом раннем уровне,
 * до подключения к базе.
 *
 * Значение читается напрямую из `process.env`, а не из `serverEnv`, потому что
 * этот файл используется в middleware. Middleware выполняется в отдельной среде,
 * где нет доступа к базе данных и файловой системе, и не должен тянуть за собой
 * серверный код. Корректность самого значения при этом гарантирована: правила
 * для `AUTH_ENABLED` проверяются при старте приложения в `env.server.ts`.
 */

/**
 * Включена ли проверка входа.
 *
 * Пока авторизация не реализована (Этап 2), закрытая зона доступна без входа —
 * иначе каркас страниц невозможно посмотреть.
 *
 * В производственной среде выключить это нельзя: приложение с `AUTH_ENABLED`,
 * отличным от `true`, просто не запустится (см. `env.schema.ts`).
 */
export const AUTH_ENABLED = process.env.AUTH_ENABLED === 'true'
