import { getLogger } from '@/shared/logger'

/**
 * Задача-пульс.
 *
 * Выполняется раз в пять минут и просто пишет строку в журнал.
 * Смысл в том, чтобы отличить «задач нет» от «фоновый процесс упал
 * три дня назад, и никто не заметил».
 *
 * Без такой задачи молчание фонового процесса выглядит точно так же,
 * как его нормальная работа в спокойный день. А от него зависят проверка
 * подписок и уведомления — вещи, поломку которых участники обнаружат
 * раньше нас.
 */
export function runHeartbeat(): void {
  getLogger().info({ job: 'heartbeat' }, 'фоновые задачи работают')
}
