import { bigserial, boolean, index, pgTable, primaryKey, text, uuid } from 'drizzle-orm/pg-core'

import { users } from '@/modules/identity/schema'
import { createdAt, timestampTz } from '@/shared/db/columns'

/**
 * Уведомления.
 *
 * ─────────────────────────────────────────────────────────────────
 * СОЗДАЮТСЯ И ХРАНЯТСЯ НА ПЛАТФОРМЕ, ДОСТАВЛЯЮТСЯ ЧЕРЕЗ TELEGRAM
 *
 * Не наоборот. Отправить сообщение ботом и забыть — самый простой
 * путь, и он ломает главный принцип: платформа обязана работать при
 * недоступном Telegram (PRD v0.1 §7.5).
 *
 * Поэтому строка появляется всегда, независимо от того, дошло ли
 * сообщение. Лента в интерфейсе показывает историю даже тому, у кого
 * мессенджер заблокирован, а `sent_at` отвечает на вопрос «почему мне
 * не пришло» без похода в логи.
 * ─────────────────────────────────────────────────────────────────
 *
 * Таблица существовала с Этапа 2 в схеме модуля `audit` и переехала
 * сюда на шаге 10.3. Имя и колонки не менялись, миграции не потребовалось.
 */
export const notifications = pgTable(
  'notifications',
  {
    id: bigserial('id', { mode: 'bigint' }).primaryKey(),

    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),

    /**
     * Ключ типа из каталога в коде, а не ссылка на таблицу типов.
     *
     * Текстом намеренно: старый тип, которого в каталоге больше нет,
     * должен остаться в истории читаемым, а не превратиться в висящую
     * ссылку или помешать удалить строку каталога.
     */
    type: text('type').notNull(),

    /**
     * Заголовок и текст сохраняются целиком, а не собираются при показе.
     *
     * Разбор потом переименуют, эфир отменят, урок перенесут — а
     * уведомление обязано остаться тем, что человек получил. Собирать
     * текст заново значило бы переписывать прошлое.
     */
    title: text('title').notNull(),
    body: text('body'),

    /** Куда ведёт нажатие. Адрес внутри платформы */
    actionUrl: text('action_url'),

    /** Куда фактически доставлено: ['web'] или ['web', 'telegram'] */
    channels: text('channels').array().notNull().default([]),

    createdAt: createdAt(),

    /**
     * Когда ушло в Telegram. `null` — ещё не отправлено или не будет.
     *
     * Это же поле служит очередью для сводки: неотправленные уведомления
     * с доставкой «сводкой» ночная задача собирает в одно сообщение.
     */
    sentAt: timestampTz('sent_at'),

    readAt: timestampTz('read_at'),
  },
  (table) => [
    // Лента человека: всё подряд, свежее сверху
    index('notifications_user_idx').on(table.userId, table.createdAt),
  ],
)

/**
 * Личные настройки доставки.
 *
 * ─────────────────────────────────────────────────────────────────
 * ХРАНИМ ТОЛЬКО ОТКЛОНЕНИЯ ОТ ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ
 *
 * Не «строка на каждый тип для каждого человека»: тогда новый тип
 * потребовал бы миграции, вписывающей его двумстам пятидесяти людям,
 * а забытая вставка означала бы человека, который молча не получает
 * половину уведомлений.
 *
 * Пусто — значит «как задумано». Ровно тот же приём, что у персональных
 * исключений в правах (PRD v0.3 §2).
 * ─────────────────────────────────────────────────────────────────
 */
export const notificationPreferences = pgTable(
  'notification_preferences',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),

    type: text('type').notNull(),

    enabled: boolean('enabled').notNull(),

    createdAt: createdAt(),
  },
  (table) => [primaryKey({ columns: [table.userId, table.type] })],
)
