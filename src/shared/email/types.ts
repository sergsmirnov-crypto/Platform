/**
 * Письмо и тот, кто умеет его отправить.
 *
 * Модули платформы работают с этим интерфейсом, а не с почтовым сервисом
 * напрямую (ARCHITECTURE §10). Смена сервиса рассылки — новый файл
 * отправителя и строка в настройках, а не правка входа на платформу.
 */

export type EmailMessage = {
  to: string
  subject: string
  /** Обычный текст. Обязателен: часть почтовых программ показывает только его */
  text: string
  /** Оформленная версия. Необязательна */
  html?: string
}

export interface EmailSender {
  /**
   * Отправляет письмо.
   *
   * Неудача — ошибка `upstream_unavailable`: сервис рассылки недоступен
   * или отказал. Вызывающий код показывает человеку «не удалось отправить
   * письмо, попробуйте ещё раз», а не падает.
   */
  send(message: EmailMessage): Promise<void>
}
