import { clsx } from 'clsx'
import { twMerge } from 'tailwind-merge'

import type { ClassValue } from 'clsx'

/**
 * Склеивает классы и разрешает конфликты между ними.
 *
 * Без этого `cn('px-4', 'px-6')` дало бы оба класса сразу, и какой из них
 * победит, зависело бы от порядка в собранном файле стилей. С `cn` побеждает
 * последний — то есть тот, что передан снаружи компонента.
 *
 * Практический смысл: компонент задаёт разумные значения по умолчанию,
 * а место использования всегда может их переопределить.
 */
export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs))
}
