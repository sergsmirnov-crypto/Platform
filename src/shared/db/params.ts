import { sql } from 'drizzle-orm'

import type { SQL } from 'drizzle-orm'

/**
 * Дата как значение внутри «сырого» куска SQL.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ЭТО НУЖНО
 *
 * В обычных условиях (`eq`, `lt`, `gt` по колонке) драйвер знает тип
 * колонки и сам превращает `Date` в значение, понятное PostgreSQL.
 * Внутри выражения, написанного строкой, — `sql\`... >= ${date}\`` —
 * знать этого неоткуда: там нет колонки, есть только параметр. Драйвер
 * получает объект `Date` и падает с сообщением, которое ни на что
 * не намекает: «string argument must be of type string».
 *
 * Ошибка коварна тем, что проверка типов её не видит: TypeScript
 * считает такой код совершенно нормальным, и всё ломается только
 * при обращении к базе — то есть на живой странице у пользователя.
 *
 * Здесь дата превращается в строку по стандарту ISO и получает явное
 * указание типа. Дальше PostgreSQL разбирает её сам, однозначно
 * и без зависимости от настроек локали сервера.
 * ─────────────────────────────────────────────────────────────────
 *
 * Правило: в шаблонах `sql\`\`` даты передавать только через эту функцию.
 *
 * @example
 * sql`${songs.publishedAt} >= ${timestampParam(since)}`
 */
export function timestampParam(value: Date): SQL {
  return sql`${value.toISOString()}::timestamptz`
}
