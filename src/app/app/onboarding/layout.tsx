import { redirect } from 'next/navigation'

import { getSession } from '@/modules/identity/current-user'
import { AUTH_ENABLED } from '@/shared/config/features'
import { routes } from '@/shared/routes'

/**
 * Разметка знакомства.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЗДЕСЬ СВОЯ РАЗМЕТКА, А НЕ ОБЩАЯ
 *
 * Знакомство лежит внутри `/app`, но общей разметки закрытой зоны
 * не наследует: этот файл её замещает. Ни бокового меню, ни шапки,
 * ни нижней панели.
 *
 * Меню на экране знакомства предлагает уйти. Человек нажмёт «Эфиры»,
 * попадёт в пустой список — подписка оформлена минуту назад, смотреть
 * он ничего не успел, — и первое впечатление сложится именно там.
 * Знакомство длится четыре экрана; всё это время платформа ведёт,
 * а не предлагает выбор.
 * ─────────────────────────────────────────────────────────────────
 *
 * Проверка входа здесь своя, потому что общей разметки нет. Проверки
 * подписки нет намеренно: человек без действующей подписки должен
 * согласиться с документами и заполнить профиль — иначе он попадёт
 * на экран продления, не имея возможности даже прочитать оферту,
 * по которой платит.
 */
export default async function OnboardingLayout({ children }: { children: React.ReactNode }) {
  if (AUTH_ENABLED) {
    const session = await getSession()

    if (!session) {
      redirect(routes.home())
    }
  }

  return <div className="bg-surface min-h-dvh">{children}</div>
}
