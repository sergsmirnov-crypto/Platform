import { pgEnum } from 'drizzle-orm/pg-core'

/**
 * Перечисления, общие для нескольких модулей содержимого.
 *
 * Здесь лежит ровно одно понятие — жизненный цикл публикации. Оно
 * одинаково у разборов, уроков, эфиров и новостей, и это не совпадение:
 * «черновик → запланировано → опубликовано → в архиве» — это способ
 * работы кураторов, а не свойство разборов.
 *
 * Почему не в модуле разборов, где оно понадобилось первым: тогда модули
 * курса, эфиров и новостей зависели бы от схемы разборов ради значения,
 * которое разборам не принадлежит. Такая зависимость выглядит безобидно
 * ровно до того дня, когда разборы понадобится переделать.
 *
 * Правило для будущего: сюда попадает только то, что нужно **трём и более**
 * модулям и не принадлежит ни одному из них. Всё остальное живёт в своём
 * модуле.
 */

/**
 * Состояние публикации.
 *
 * `draft`     — черновик, виден только кураторам
 * `scheduled` — время публикации назначено, но ещё не наступило
 * `published` — видно участникам
 * `archived`  — снято с публикации, но не удалено: ссылки и прогресс живы
 */
export const publicationStatusEnum = pgEnum('publication_status', [
  'draft',
  'scheduled',
  'published',
  'archived',
])

export type PublicationStatus = (typeof publicationStatusEnum.enumValues)[number]

/**
 * К чему можно привязать материал или метку.
 *
 * Общий список для полиморфных связей: `attachments` в модуле медиа
 * и `taggables` в модуле меток. Значения добавляются по мере появления
 * новых видов содержимого.
 */
export const contentEntityEnum = pgEnum('content_entity', [
  'song',
  'arrangement',
  'arrangement_section',
  'lesson',
  'stream',
  'news_post',
])

export type ContentEntity = (typeof contentEntityEnum.enumValues)[number]
