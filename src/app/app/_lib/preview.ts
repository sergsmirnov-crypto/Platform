import type { EffectivePermissions } from '@/modules/access'
import { safeReturnTo } from '@/modules/identity/return-to'
import { routes } from '@/shared/routes'

/**
 * Режим «смотреть как участник» — правила.
 *
 * Куратор одной кнопкой видит платформу глазами обычного участника:
 * без кнопок «Редактировать», без раздела «Управление», без черновиков
 * (PRD v0.3 §4.3). Нужно это по практической причине: у куратора всегда
 * включён показ черновиков, поэтому он физически не может заметить,
 * что опубликованный разбор выглядит сломанным — у него на экране всё
 * на месте, а у участника пусто.
 *
 * Здесь только чистые функции: они ничего не знают ни о cookie, ни о базе,
 * ни о Next.js. Поэтому их можно полностью покрыть тестами.
 *
 * ─────────────────────────────────────────────────────────────────
 * ГЛАВНОЕ СВОЙСТВО МОДЕЛИ: режим только ОТНИМАЕТ права и никогда
 * не добавляет. Из этого следует, что состояние режима можно держать
 * в браузере: даже подделанная cookie даёт человеку меньше возможностей,
 * а не больше. Ни одна проверка доступа от этого не ослабевает.
 * ─────────────────────────────────────────────────────────────────
 */

/**
 * Имя cookie с состоянием режима.
 *
 * Режим привязан к устройству, а не к человеку: куратор может проверять
 * вид страницы на телефоне, оставаясь в управлении на ноутбуке. Храни мы
 * это в базе, включение на телефоне переключило бы и ноутбук.
 *
 * Префикс `__Host-` в производственной сборке — требование браузера:
 * cookie с таким именем принимается только по HTTPS, без указания домена
 * и с путём `/`. На локальной машине HTTPS нет, поэтому там имя обычное.
 */
export const PREVIEW_COOKIE_NAME =
  process.env.NODE_ENV === 'production' ? '__Host-gc_view_as_member' : 'gc_view_as_member'

/** Единственное значение, которое считается включённым режимом */
export const PREVIEW_COOKIE_VALUE = '1'

/** Пустой набор прав — ровно то, что есть у обычного участника клуба */
const NO_PERMISSIONS: EffectivePermissions = new Map()

/** Просил ли браузер включить режим */
export function isPreviewRequested(rawCookieValue: string | undefined | null): boolean {
  return rawCookieValue === PREVIEW_COOKIE_VALUE
}

/**
 * Включён ли режим на самом деле.
 *
 * Мало того, что cookie стоит: у человека должны быть управляющие права.
 * Иначе обычный участник со случайно оставшейся cookie увидел бы полосу
 * «вы смотрите глазами участника» — сообщение, которое ему ничего
 * не говорит и выглядит поломкой.
 */
export function resolvePreviewState(options: {
  requested: boolean
  hasRealPermissions: boolean
}): boolean {
  return options.requested && options.hasRealPermissions
}

/**
 * Права с учётом режима.
 *
 * В режиме просмотра набор прав пустой — не «убрали управляющие»,
 * а «убрали все». У обычного участника ролей нет вообще, значит пустой
 * набор буквально и есть «глазами участника». Это проще и предсказуемее,
 * чем список исключений, который пришлось бы поддерживать вручную
 * при каждом новом праве.
 */
export function maskPermissions(
  real: EffectivePermissions,
  isPreview: boolean,
): EffectivePermissions {
  return isPreview ? NO_PERMISSIONS : real
}

/** Относится ли адрес к разделу «Управление» */
export function isManagePath(path: string): boolean {
  const manage = routes.app.manage.index()
  return path === manage || path.startsWith(`${manage}/`)
}

/**
 * Куда вести человека после переключения режима.
 *
 * Обычно — обратно на ту же страницу: человек включает режим, чтобы
 * посмотреть на страницу, где он сейчас находится.
 *
 * Исключение — раздел «Управление». Включив режим там, человек попал бы
 * на страницу, которой в этом режиме не существует. Уводим на главную.
 *
 * Адрес приходит из браузера, поэтому проверяется тем же способом, что
 * и адрес возврата после входа: принимаются только внутренние пути.
 * Иначе кнопка «Смотреть как участник» стала бы открытым перенаправлением.
 */
export function pathAfterPreviewChange(rawPath: string | null | undefined, entering: boolean) {
  const path = safeReturnTo(rawPath)

  if (entering && isManagePath(path)) {
    return routes.app.dashboard()
  }

  return path
}
