import { slugify } from '@/shared/utils/slug'

/**
 * Начальный набор меток.
 *
 * Заполняется при первом запуске и дальше пополняется кураторами
 * из интерфейса. Смысл начального набора — чтобы фильтры каталога
 * не встречали первого куратора пустотой, в которую непонятно, что
 * вписывать: список задаёт словарь и уровень дробности.
 *
 * ⚠️ Жанры обязаны совпадать со списком в профиле участника
 * (`identity/profile.ts`). Совпадение проверяется тестом: разойдясь,
 * списки превратили бы «подобрать разбор по любимым жанрам» в подбор,
 * который ничего не находит. Тест — единственная причина, по которой
 * это правило не забудется через полгода.
 */

/**
 * Виды меток.
 *
 * Объявлены здесь, а не в описании таблиц: этот список нужен и браузеру
 * (фильтры каталога), а описание таблиц тянет за собой драйвер базы.
 * Перечисление в базе собирается из этого же списка — разойтись они
 * не могут.
 */
export const TAG_KINDS = ['genre', 'technique', 'mood'] as const

export type TagKind = (typeof TAG_KINDS)[number]

export type TagSeed = {
  slug: string
  name: string
  kind: TagKind
  orderIndex: number
}

/**
 * Жанры — единый список платформы.
 *
 * Тот же самый набор используется в профиле участника («любимые жанры»):
 * модуль участников берёт его отсюда. Два списка в двух модулях
 * разошлись бы в первый же раз, когда жанр добавят в одном месте,
 * и подбор разборов по вкусам перестал бы находить что-либо.
 *
 * Порядок — по тому, насколько часто их разбирают в клубе.
 */
export const GENRE_NAMES = [
  'Рок',
  'Классический рок',
  'Русский рок',
  'Метал',
  'Панк',
  'Блюз',
  'Джаз',
  'Фолк',
  'Кантри',
  'Поп',
  'Романс и бардовская',
  'Фингерстайл',
  'Классика',
] as const

/**
 * Техники.
 *
 * То, чему человек учится, а не то, что он слушает. Разделение важно
 * для подбора: «хочу научиться перебору» и «люблю русский рок» —
 * запросы разной природы, и складывать их в один список фильтров
 * значит мешать и тому и другому.
 */
const TECHNIQUE_NAMES = [
  'Бой',
  'Перебор',
  'Фингерстайл',
  'Соло',
  'Баррэ',
  'Слайд',
  'Теппинг',
  'Флажолеты',
  'Медиатор',
  'Глушение',
] as const

/** Настроение. Нужно подборкам: «под гитару у костра», «спокойное вечером» */
const MOOD_NAMES = ['Спокойное', 'Energetic', 'Грустное', 'Праздничное', 'У костра'] as const

/**
 * Адресное имя метки включает её вид.
 *
 * Не украшение: «Фингерстайл» — одновременно жанр и техника, и это
 * не ошибка составителя списка. Как жанр это то, что человек слушает,
 * как техника — то, чему он учится, и фильтруют по ним разное.
 * Без вида в имени две разные метки получили бы один адрес.
 *
 * Обнаружено тестом на повторяющиеся имена, а не в бою.
 */
export function tagSlug(kind: TagKind, name: string): string {
  return `${kind}-${slugify(name)}`
}

function build(names: readonly string[], kind: TagKind): TagSeed[] {
  return names.map((name, index) => ({
    slug: tagSlug(kind, name),
    name,
    kind,
    orderIndex: index,
  }))
}

export const GENRE_TAGS: TagSeed[] = build(GENRE_NAMES, 'genre')
export const TECHNIQUE_TAGS: TagSeed[] = build(TECHNIQUE_NAMES, 'technique')
export const MOOD_TAGS: TagSeed[] = build(MOOD_NAMES, 'mood')

export const TAG_SEEDS: TagSeed[] = [...GENRE_TAGS, ...TECHNIQUE_TAGS, ...MOOD_TAGS]

/** Как называется вид метки в интерфейсе */
export const TAG_KIND_LABELS: Record<TagKind, string> = {
  genre: 'Жанр',
  technique: 'Техника',
  mood: 'Настроение',
}
