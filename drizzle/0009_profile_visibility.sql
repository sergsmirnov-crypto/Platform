-- Видимость визитки участника (шаг 8.2)
--
-- По умолчанию «private», и это не осторожничанье: человек,
-- регистрировавшийся год назад, не давал согласия показывать свой город
-- и рассказ о себе полутора сотням людей. Согласие нельзя получить
-- задним числом настройкой по умолчанию.
--
-- «club» означает «видно участникам клуба», а не «видно интернету»:
-- платформа закрыта целиком, публичной витрины у визиток нет.

