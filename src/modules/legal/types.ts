/**
 * Понятия модуля правовых документов.
 */

/**
 * Какие документы есть на платформе.
 *
 * Список закрыт и живёт в коде: каждый документ — это отдельная страница,
 * отдельный текст и, для двух из трёх, отдельная запись о согласии.
 * Добавление документа — это работа разработчика, а не заполнение формы.
 */
export const LEGAL_DOCUMENT_IDS = ['offer', 'privacy', 'contacts'] as const

export type LegalDocumentId = (typeof LEGAL_DOCUMENT_IDS)[number]

/**
 * Правовой документ платформы.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ТЕКСТ В КОДЕ, А НЕ В НАСТРОЙКАХ ПЛАТФОРМЫ
 *
 * Страница «О клубе» правится владельцем из интерфейса — и правильно:
 * расписание эфиров меняется чаще, чем выходят релизы. С офертой так
 * нельзя, и причина не в осторожности.
 *
 * Участник не просто читает оферту — он с ней *соглашается*, и платформа
 * записывает факт согласия. Если текст можно поменять из админки без
 * истории версий, то запись «согласился 12 марта» перестаёт что-либо
 * значить: неизвестно, что было на экране в этот момент. Документ,
 * с которым согласились, обязан быть неизменяемым; меняется только
 * редакция, и у неё свой номер.
 *
 * Поэтому правка текста — это коммит с новым номером редакции. Для
 * документа, который меняется раз в год, это правильная цена.
 * ─────────────────────────────────────────────────────────────────
 */
export type LegalDocument = {
  id: LegalDocumentId

  /** Заголовок страницы и пункта меню */
  title: string

  /** Короткое имя для навигации между документами */
  shortTitle: string

  /** Одна строка о том, что внутри. Показывается под заголовком */
  summary: string

  /**
   * Номер редакции. Растёт при каждом изменении текста.
   *
   * Именно он сохраняется в записи о согласии. Правка текста без смены
   * номера ломает смысл записи, поэтому её ловит тест `versions.test.ts`.
   */
  version: number

  /** Дата вступления редакции в силу, в виде `ГГГГ-ММ-ДД` */
  effectiveDate: string

  /**
   * Требуется ли согласие участника.
   *
   * У «Контактов» согласия нет: это справочная страница, а не договор.
   * Требовать согласия со списком адресов было бы бессмысленным
   * действием, которое обесценивает согласие с остальными двумя.
   */
  requiresAcceptance: boolean

  /**
   * Текст документа в Markdown, с местами для реквизитов вида
   * `{{EMAIL}}`. Подстановка — в `placeholders.ts`.
   */
  body: string
}

/** Документ, с которым участник обязан согласиться */
export type AcceptableDocumentId = Extract<LegalDocumentId, 'offer' | 'privacy'>

/** Согласие с конкретной редакцией конкретного документа */
export type AcceptedVersion = {
  document: AcceptableDocumentId
  version: number
  acceptedAt: Date
}
