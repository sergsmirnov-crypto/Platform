/**
 * Процесс фоновых задач.
 *
 * Запускается отдельно от сайта: `pnpm worker`.
 *
 * Почему отдельный процесс, а не внутри приложения:
 *
 *   1. При перезапуске сайта задачи не обрываются на середине.
 *   2. В режиме разработки приложение перезагружается при каждой правке
 *      файла — задачи запускались бы заново десятки раз за час.
 *   3. Тяжёлая задача (обработка видео) не замедляет открытие страниц.
 *
 * Код при этом общий: процесс задач пользуется теми же модулями, что и сайт.
 *
 * Этот файл — только загрузчик. Он читает настройки из файла и лишь потом
 * подключает основную логику. Порядок важен: импорты в JavaScript
 * выполняются раньше любого кода, поэтому загрузить настройки
 * и импортировать модули в одном файле невозможно.
 */
import { loadEnvFile } from 'node:process'

try {
  loadEnvFile('.env')
} catch {
  // На боевом сервере переменные приходят из окружения, файла .env нет
}

await import('./main')
