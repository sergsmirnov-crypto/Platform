/**
 * Кто читает содержимое платформы.
 *
 * ─────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОТДЕЛЬНОЕ ПОНЯТИЕ ВМЕСТО ПРОСТОГО `userId`
 *
 * Все разделы содержимого — разборы, курс, эфиры, новости — отвечают
 * на один и тот же вопрос перед каждым чтением: показывать ли этому
 * человеку неопубликованное. Ответ зависит не только от прав, но и
 * от режима «смотреть как участник»: куратор, включивший его, обязан
 * увидеть платформу ровно такой, какой её видит обычный человек.
 *
 * Режим живёт в cookie, то есть в слое приложения. Модули содержимого
 * о нём знать не могут и не должны: тот же код работает в процессе
 * фоновых задач, где браузера нет вовсе. Поэтому решение принимается
 * один раз наверху и приезжает в модуль готовым — этой структурой.
 *
 * Собирать её вручную нельзя. Единственный законный способ — helper
 * `getContentViewer` в слое приложения; прямое обращение к правам
 * оттуда запрещено правилом линтера.
 * ─────────────────────────────────────────────────────────────────
 */
export type ContentViewer = {
  userId: string
  /**
   * Видит ли человек черновики и запланированное.
   *
   * В режиме «смотреть как участник» здесь всегда `false`, даже
   * у владельца платформы.
   */
  canSeeDrafts: boolean
}

/**
 * Читатель без входа: публичная витрина, поисковые роботы.
 *
 * Отдельное значение, а не `userId: null`, потому что пустой
 * идентификатор в проверке прав — это способ однажды случайно показать
 * черновики тому, у кого прав нет вовсе.
 */
export const ANONYMOUS_VIEWER = { userId: '', canSeeDrafts: false } as const satisfies ContentViewer
