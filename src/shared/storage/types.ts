/**
 * Хранилище файлов: договор, одинаковый для любого поставщика.
 *
 * Приложение работает с этим набором функций и не знает, лежит ли файл
 * в S3 у Selectel, у Timeweb или на диске машины разработчика. Смена
 * поставщика — новый файл рядом и строка в настройках, а не переделка
 * половины проекта (ARCHITECTURE §10).
 *
 * Это прямо закрывает риск «оплата зарубежного сервиса из России
 * перестала проходить» (PRD v0.2 §7, риск 8).
 *
 * ─────────────────────────────────────────────────────────────────
 * ДВА ВИДА ФАЙЛОВ, И РАЗНИЦА МЕЖДУ НИМИ ПРИНЦИПИАЛЬНАЯ.
 *
 *   public  — аватары, обложки. Отдаются напрямую из сети доставки,
 *             без участия платформы. Адрес постоянный, браузер кэширует.
 *
 *   private — табы, PDF, материалы. Отдаются только по ссылке
 *             с коротким сроком жизни, выданной после проверки подписки.
 *             Постоянного адреса не существует: пересланная ссылка
 *             протухает за минуты (PRD v0.2 §2.1).
 * ─────────────────────────────────────────────────────────────────
 *
 * Файлы никогда не проходят через наш сервер при ЧТЕНИИ: мы проверяем
 * права и выдаём ссылку, дальше браузер идёт в хранилище напрямую.
 * Поэтому небольшого сервера хватает при любом объёме скачиваний.
 */

/** Кому виден файл. Определяет и место хранения, и способ выдачи */
export type FileVisibility = 'public' | 'private'

export type StoredFile = {
  /** Путь внутри хранилища: 'public/avatars/<id>/<файл>.webp' */
  key: string
  size: number
  contentType: string
}

export type PutFileInput = {
  key: string
  body: Buffer | Uint8Array
  contentType: string
  visibility: FileVisibility
  /**
   * Сколько браузеру и сети доставки разрешено держать файл у себя.
   * Для публичных картинок с неизменным именем — сколь угодно долго:
   * при замене аватара имя меняется, поэтому устаревшее не покажется
   */
  cacheSeconds?: number
}

export interface StorageProvider {
  /** Название для журнала и страницы состояния */
  readonly name: string

  put(input: PutFileInput): Promise<StoredFile>

  delete(key: string): Promise<void>

  /**
   * Постоянный адрес публичного файла.
   *
   * Для закрытых файлов не имеет смысла и не должен вызываться:
   * у них постоянного адреса нет по определению.
   */
  getPublicUrl(key: string): string

  /**
   * Временный адрес закрытого файла.
   *
   * @param expiresInSeconds срок жизни ссылки. Короткий намеренно:
   *        пересылать такую ссылку бесполезно
   */
  getSignedUrl(key: string, expiresInSeconds: number, options?: SignedUrlOptions): Promise<string>
}

export type SignedUrlOptions = {
  /**
   * Под каким именем файл сохранится у человека.
   *
   * Без этого браузер берёт имя из адреса, а в адресе лежит ключ
   * хранилища — «a3f21c-1.pdf». Участник скачивает пять таких табов
   * и не может отличить их друг от друга. Имя задаётся при подписи
   * ссылки, поэтому подменить его нельзя.
   */
  downloadName?: string

  /**
   * Показать файл в браузере, а не сохранить на диск.
   *
   * Нужно табам в режиме репетиции: PDF со встроенным просмотрщиком
   * читается рядом с видео, а тот же файл с заголовком «сохранить»
   * браузер молча скачивает и ничего не показывает (шаг 10.6)
   */
  inline?: boolean
}
