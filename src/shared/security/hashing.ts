import { createHmac, randomBytes } from 'node:crypto'

/**
 * Хеширование секретов и персональных данных.
 *
 * Два разных применения, но приём один и тот же.
 *
 * **Ключи сессий.** В базе лежит не сам ключ, а его хеш. Если содержимое
 * базы утечёт, войти по этим данным будет нельзя: из хеша ключ не восстановить.
 *
 * **IP-адреса.** Адрес — персональные данные. Он нужен, чтобы человек видел
 * в профиле список своих устройств и мог заметить чужой вход, но хранить его
 * в открытом виде незачем: сравнивать хеши так же удобно.
 *
 * Почему HMAC, а не обычный SHA-256: HMAC подмешивает секрет приложения.
 * Тот, кто получил только копию базы, не сможет проверить догадку
 * «а не этот ли это адрес» — без секрета вычислить хеш не выйдет.
 * Для коротких предсказуемых значений вроде IP это важно: их полный
 * перебор занял бы минуты.
 *
 * Функции чистые: секрет приходит аргументом, а не читается из окружения.
 * Так их можно покрыть тестами, не поднимая приложение.
 */

/**
 * Длина ключа сессии в байтах.
 *
 * 32 байта — это 256 бит случайности. Подобрать такой ключ перебором
 * невозможно при любых мыслимых вычислительных мощностях.
 */
const TOKEN_BYTES = 32

/**
 * Создаёт случайный ключ сессии.
 *
 * Кодировка `base64url` выбрана намеренно: результат безопасен для передачи
 * в cookie и в адресе страницы — в нём нет символов `+`, `/` и `=`,
 * которые пришлось бы экранировать.
 */
export function generateToken(bytes: number = TOKEN_BYTES): string {
  return randomBytes(bytes).toString('base64url')
}

/**
 * Считает хеш значения с использованием секрета приложения.
 *
 * @param value  что хешируем: ключ сессии или IP-адрес
 * @param secret секрет приложения (`SESSION_SECRET`)
 */
export function hashWithSecret(value: string, secret: string): string {
  if (!secret) {
    throw new Error('Не задан секрет для хеширования (SESSION_SECRET)')
  }

  return createHmac('sha256', secret).update(value).digest('hex')
}
