import { integer, pgEnum, pgTable, text, uniqueIndex, uuid } from 'drizzle-orm/pg-core'

import { users } from '@/modules/identity/schema'
import { primaryId, timestampTz } from '@/shared/db/columns'

/**
 * Согласия с правовыми документами.
 *
 * ─────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЗАПИСЬ НА КАЖДУЮ РЕДАКЦИЮ, А НЕ ФЛАГ «СОГЛАСЕН»
 *
 * Логичное первое решение — колонка `users.accepted_terms_at`. Она
 * отвечает на вопрос «согласен ли», но нужен ответ на вопрос
 * «с чем именно согласен».
 *
 * Оферта будет меняться: изменится цена, добавится пункт, юрист поправит
 * формулировку. После первой же правки дата в такой колонке перестаёт
 * что-либо доказывать — неизвестно, какой текст человек видел. А отдельная
 * запись на каждую редакцию отвечает точно: согласился с редакцией 2
 * двенадцатого марта, с редакцией 3 — не согласился, значит при следующем
 * входе увидит экран согласия.
 *
 * Строки не обновляются и не удаляются — только добавляются. Это журнал,
 * а не состояние.
 * ─────────────────────────────────────────────────────────────────
 */

/**
 * Документы, с которыми соглашаются.
 *
 * «Контактов» здесь нет: с адресом для обращений не соглашаются.
 * Собственное перечисление, а не общий список документов, потому что
 * значение `contacts` в этой таблице было бы бессмыслицей, которую база
 * пропустила бы молча.
 */
export const legalDocumentEnum = pgEnum('legal_document', ['offer', 'privacy'])

export type LegalDocumentEnumValue = (typeof legalDocumentEnum.enumValues)[number]

export const legalAcceptances = pgTable(
  'legal_acceptances',
  {
    id: primaryId(),

    /**
     * Удаление вместе с участником.
     *
     * Согласие имеет смысл только как согласие конкретного человека
     * с конкретным договором. Учётной записи нет — нет и второй стороны,
     * хранить обезличенную запись «кто-то согласился» незачем. Документы
     * об оплате, которые надо хранить пять лет, живут отдельно
     * и от этой таблицы не зависят.
     */
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),

    document: legalDocumentEnum('document').notNull(),

    /** Номер редакции, с которой человек согласился */
    version: integer('version').notNull(),

    acceptedAt: timestampTz('accepted_at').notNull().defaultNow(),

    /**
     * Обстоятельства согласия.
     *
     * IP — хешем, как везде в проекте: адрес относится к персональным
     * данным. Для спорной ситуации важно не «откуда», а «то же ли это
     * устройство», и на этот вопрос хеш отвечает.
     */
    ipHash: text('ip_hash'),
    userAgent: text('user_agent'),
  },
  (table) => [
    // Согласие с одной редакцией — один раз. Повторное нажатие кнопки
    // не должно создавать второй записи: иначе в карточке участника
    // появятся два одинаковых согласия с разным временем
    uniqueIndex('legal_acceptances_unique_idx').on(table.userId, table.document, table.version),
  ],
)
